// Renders a generated poem: one span per syllable, with the constrained
// positions marked (B/T) and rhyming syllables highlighted.
import { type Poem, lineText } from "../decode/generate";
import { TONE_PATTERN, checkLines } from "../text/lucbat";
import { RhymeMatch } from "../text/rhyme";

function el<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  className?: string,
  text?: string,
): HTMLElementTagNameMap[K] {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

export function renderPoem(target: HTMLElement, poem: Poem): void {
  target.replaceChildren();
  const report = checkLines(poem.lines.map(lineText));
  const rhymeAt = new Map<string, string>();
  for (const link of report.rhymes) {
    if (link.match === RhymeMatch.None) continue;
    const kind = link.match === RhymeMatch.Exact ? "exact rhyme" : "near rhyme";
    rhymeAt.set(`${link.first[0]}:${link.first[1]}`, kind);
    rhymeAt.set(`${link.second[0]}:${link.second[1]}`, kind);
  }
  poem.lines.forEach((line, index) => {
    const length = index % 2 === 0 ? 6 : 8;
    const row = el("div", `line ${length === 6 ? "six" : "eight"}`);
    if (line.fromPrompt) row.classList.add("from-prompt");
    row.style.animationDelay = `${index * 120}ms`;
    line.syllables.forEach((syllable, i) => {
      const position = i + 1;
      const word = el("span", "word");
      const text = el("span", undefined, i === 0 ? capitalize(syllable) : syllable);
      const need = TONE_PATTERN[length][position];
      const mark = el("span", "mark", need === undefined ? "" : need ? "B" : "T");
      const rhyme = rhymeAt.get(`${index + 1}:${position}`);
      if (rhyme) word.classList.add("rhyme");
      const parts = [line.fromPrompt ? "from your prompt" : null, rhyme ?? null];
      const p = line.confidence[i];
      if (p !== undefined) parts.push(`p = ${p.toFixed(3)} among the allowed syllables`);
      word.title = parts.filter(Boolean).join("; ");
      word.append(text, mark);
      row.append(word);
    });
    target.append(row);
  });
  const relaxed = poem.lines.filter((l) => l.relaxed).length;
  const caption = el(
    "figcaption",
    undefined,
    `Generated by the model. Lục bát check: ${report.violations.length} violations${relaxed ? `, rhyme relaxed in ${relaxed} line(s)` : ""}.`,
  );
  target.append(caption);
}

function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

export function renderCheck(target: HTMLElement, text: string): void {
  target.replaceChildren();
  let report: ReturnType<typeof checkLines>;
  try {
    report = checkLines(text.split(/[\n/|]+/).filter((l) => l.trim().length > 0));
  } catch (error) {
    target.append(el("p", "problems", (error as Error).message));
    return;
  }
  for (const line of report.lines) {
    const row = el("div", "row");
    const pattern = line.parsed.map((s) => (s === null ? "?" : s.tone <= 1 ? "B" : "T")).join("");
    row.append(
      el("span", "num", String(line.number)),
      el("span", "pattern", pattern),
      el("span", undefined, line.syllables.join(" ")),
    );
    target.append(row);
  }
  if (report.violations.length === 0) {
    const exact = report.rhymes.filter((r) => r.match === RhymeMatch.Exact).length;
    const near = report.rhymes.filter((r) => r.match === RhymeMatch.Near).length;
    target.append(el("p", "ok", `Valid lục bát. Rhymes: ${exact} exact, ${near} near.`));
    return;
  }
  const list = el("ul", "problems");
  for (const v of report.violations) {
    const where = v.position ? `, syllable ${v.position}` : "";
    list.append(el("li", undefined, `Line ${v.line}${where}: ${v.message}`));
  }
  target.append(list);
}
